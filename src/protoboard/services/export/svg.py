"""SVG board exporter — renders top layer to a standalone SVG file.

Routes through :func:`paint_snapshot` so SVG output is pixel-for-pixel
equivalent to BoardView (modulo anti-aliasing implementation
differences).  The hand-rolled ElementTree path used previously is
gone — it could not keep up with the renderer set (strip tracks,
body shapes, pin-modifiers, ratsnest, etc.) and routinely fell out of
sync with the on-screen rendering.

The public signature stays compatible with existing callers and tests
that pass ``board / layout / components / instances`` directly; a
:class:`BoardSnapshot` is constructed internally.  Callers wanting
fine control (e.g. routing-target neon for documentation) can pass an
explicit snapshot via :func:`export_svg_from_snapshot`.
"""

from __future__ import annotations

import io
import uuid
from typing import TYPE_CHECKING

from PySide6.QtCore import QBuffer, QByteArray, QIODevice, QRectF, QSizeF
from PySide6.QtGui import QPainter
from PySide6.QtSvg import QSvgGenerator

from protoboard.domain.board.pad_state import PadIndex
from protoboard.domain.schematic.schematic import Schematic
from protoboard.gui.theme import DEFAULT_THEME, Theme
from protoboard.services.export.paint import paint_snapshot
from protoboard.services.export.snapshot import BoardSnapshot

if TYPE_CHECKING:
    from protoboard.domain.board.board import Board
    from protoboard.domain.components.definition import ComponentDefinition
    from protoboard.domain.components.instance import ComponentInstance
    from protoboard.domain.layout.layout import Layout


def export_svg(
    board: "Board",
    layout: "Layout",
    components: dict[str, "ComponentDefinition"],
    instances: dict[uuid.UUID, "ComponentInstance"],
    schematic: "Schematic | None" = None,
    scale: float | None = None,
    theme: Theme = DEFAULT_THEME,
) -> str:
    """Render the board to an SVG string.

    *scale* is the SVG user-unit multiplier (default :attr:`Theme.svg_scale`,
    historically 10).  The SVG viewBox covers the board plus a 1-raster
    margin (matching the legacy export) so file dimensions stay
    predictable.

    ``schematic`` may be omitted — an empty :class:`Schematic` is used,
    which simply means net-aware colouring falls back to the unassigned
    palette entry.
    """
    sch = schematic if schematic is not None else Schematic(nets={})
    pad_index = PadIndex(
        board=board, layout=layout, schematic=sch,
        components=components, instances=instances,
    )
    body_types = getattr(theme, "body_types", None) or {}
    snapshot = BoardSnapshot(
        board=board, layout=layout,
        components=components, instances=instances,
        schematic=sch, pad_index=pad_index,
        body_types=body_types, theme=theme,
    )
    return export_svg_from_snapshot(snapshot, scale=scale)


def export_svg_from_snapshot(
    snapshot: BoardSnapshot,
    *,
    scale: float | None = None,
) -> str:
    """SVG export driven by a pre-built snapshot.

    Used by the multi-panel template exporter to render top / bottom /
    mirrored variants without rebuilding the PadIndex four times.
    """
    if scale is None:
        scale = snapshot.theme.svg_scale

    b = snapshot.board.bounds
    # ViewBox covers board + 1-raster margin (matches legacy SVG export
    # so callers relying on exact dimensions still work).
    vb_w = (b.width + 2) * scale
    vb_h = (b.height + 2) * scale

    buffer = QBuffer()
    buffer.open(QIODevice.OpenModeFlag.WriteOnly)
    gen = QSvgGenerator()
    gen.setOutputDevice(buffer)
    gen.setSize(QSizeF(vb_w, vb_h).toSize())
    gen.setViewBox(QRectF(0, 0, vb_w, vb_h))
    gen.setTitle("Protoboard layout")
    gen.setDescription("Generated by protoboard-designer")
    # Make the underlying pixel-equivalent resolution explicit; without
    # this QSvgGenerator inserts its default 90 dpi which produces
    # surprising physical sizes when the SVG is rasterised downstream.
    gen.setResolution(int(round(scale / snapshot.board.raster_pitch_mm * 25.4)))

    painter = QPainter()
    painter.begin(gen)
    try:
        paint_snapshot(painter, snapshot, QRectF(0, 0, vb_w, vb_h))
    finally:
        painter.end()
    buffer.close()

    raw: QByteArray = buffer.data()
    return bytes(raw).decode("utf-8")


__all__ = ["export_svg", "export_svg_from_snapshot"]
