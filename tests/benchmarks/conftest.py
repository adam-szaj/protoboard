@pytest.fixture(scope="session")
def synthetic_medium_routed_session(qt_app, _bench_library):
    """Synthetic medium with autoroute already applied — gives a populated
    ``layout.wires`` for benches that exercise wire-aware hot paths
    (hit_test_wire, set_highlighted_net, etc.)."""
    import copy

    from protoboard.gui.session import EditorSession
    from protoboard.services.routing.autorouter import autoroute
    from tests.fixtures.synthetic_bench.generator import MEDIUM, generate_project

    bundle = generate_project(MEDIUM)
    result = autoroute(
        board=bundle.board,
        layout=copy.deepcopy(bundle.layout),
        schematic=bundle.schematic,
        components=bundle.components,
        instances=bundle.instances,
        cost_model=bundle.routing.cost_model(),
        max_rip_up_passes=2,
        max_optimize_iterations=0,
        preferred_side=bundle.routing.preferred_side,
        wire_mode=bundle.routing.wire_mode,
        max_detour_factor=bundle.routing.max_detour_factor,
    )
    routed_layout = copy.deepcopy(bundle.layout)
    for w in result.wires:
        routed_layout.wires.append(w)

    session = EditorSession(board=bundle.board, library=_bench_library)
    session.layout = routed_layout
    session.schematic = bundle.schematic
    session.instances = bundle.instances
    session.routing_settings = bundle.routing
    return session


